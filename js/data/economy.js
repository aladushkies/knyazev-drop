// Экономика «Князев-коинов» (КК): единый источник цен, вероятностей и лимитов.
// Режим «прикол, не казино» (v2.1): банк не зарабатывает — матожидание каждого
// действия ≈ 0 (проверяется Монте-Карло), комиссий нет, бонус — подарок.
// validateEconomy() проверяет инварианты (разд. 9 документа, скорректированы
// под околонулевой edge): нарушение должно ловиться тестами (npm test).
const ECON = {
  // Валюта условная, школьная: не покупается и не выводится.
  currency: 'КК',
  startBalance: 1000, // = 10 кейсов «Домашка»
  // Бонус за вход: +100 КК раз в 30 с (восстановлено поведение v1.8.11).
  // Это честный подарок: при нулевом edge банка бонус — единственный источник
  // «бесплатных» денег, и это осознанный выбор дизайна («прикол, не казино»).
  bonus: { amount: 100, cooldownMs: 30000 },
  // Продажа карточки: 100 % стоимости, комиссии нет.
  sell: { rate: 1 },
  // Апгрейд: шанс = coef · v / V (в %), кап cap %. При coef = 100 EV спина
  // ровно 0 при любом прыжке: chance·V = v. Выбор цели меняет только дисперсию.
  upgrade: { coef: 100, cap: 96 },
  // Анализ лица в MOGG стоит КК: списывается с баланса, при ошибке возвращается.
  mogg: { analysisCost: 100 },
  // Страховка перед апгрейдом: costRate · v, при неудаче карточка не сгорает.
  // При нулевом EV апгрейда страховка делает спин строго убыточным — честная
  // плата за снижение дисперсии. Выкл.
  insurance: { enabled: false, costRate: 0.25 },
  // Предметы: оценка, редкость, стоимость. Пятёрка в 50 раз дороже двойки.
  items: [
    { n: 'Двойка', g: '2', v: 20, r: 0 },
    { n: 'Тройка', g: '3', v: 60, r: 1 },
    { n: 'Четвёрка', g: '4', v: 200, r: 2 },
    { n: 'Пятёрка', g: '5', v: 1000, r: 3 }
  ],
  rarities: ['Обычный', 'Редкий', 'Эпический', 'Легендарный'],
  // Кейсы с нулевым edge: EV строго равно цене (см. тесты). Пятёрка из
  // «Домашки» — 4 %, из «Самостоятельной» — 24 %.
  cases: [
    { name: 'Домашка', price: 100, chances: [50, 30, 16, 4] },
    { name: 'Самостоятельная', price: 350, chances: [7, 21, 48, 24] }
  ]
};

// Автопроверка инвариантов. Возвращает [] при корректности, иначе список ошибок.
function validateEconomy() {
  const errs = [], items = ECON.items, cases = ECON.cases;
  // №4: стоимости строго растут с редкостью.
  for (let i = 1; i < items.length; i++) {
    if (items[i].v <= items[i - 1].v) errs.push(`инвариант 4: стоимость «${items[i].n}» не выше предыдущей редкости`);
  }
  // №1: сумма шансов каждого кейса = 100 %.
  // №2 (околонулевая экономика): |edge| ≤ 1 % — банк не зарабатывает и не раздаёт.
  const evPerPrice = [];
  for (const c of cases) {
    const sum = c.chances.reduce((a, b) => a + b, 0);
    if (Math.abs(sum - 100) > 1e-9) errs.push(`инвариант 1: шансы кейса «${c.name}» дают ${sum} %, а не 100 %`);
    const ev = c.chances.reduce((a, p, i) => a + p / 100 * items[i].v, 0);
    evPerPrice.push(ev / c.price);
    const edge = 1 - ev / c.price;
    if (Math.abs(edge) > 0.01) errs.push(`инвариант 2: edge кейса «${c.name}» = ${(edge * 100).toFixed(2)} %, допустимо ±1 %`);
  }
  // №3: |EV апгрейда| ≤ 1 % от стоимости карточки — околонулевой спин при
  // любом прыжке (линейность шанса: EV = (coef/100 − 1) · v не зависит от цели).
  const upEv = ECON.upgrade.coef / 100 - 1;
  for (let r = 0; r < items.length - 1; r++) {
    if (Math.abs(upEv) > 0.01) errs.push(`инвариант 3: EV апгрейда = ${(upEv * 100).toFixed(2)} % от карточки, допустимо ±1 %`);
    for (let t = r + 1; t < items.length; t++) {
      if (items[t].v <= items[r].v) errs.push(`инвариант 3: цель «${items[t].n}» не дороже «${items[r].n}»`);
    }
  }
  // №5: бонус — подарок, но не чаще раза в 30 с и не более 100 КК за раз.
  if (!(ECON.bonus.amount > 0 && ECON.bonus.amount <= 100)) errs.push(`инвариант 5: бонус ${ECON.bonus.amount} КК вне коридора 0…100`);
  if (!(ECON.bonus.cooldownMs >= 30000)) errs.push(`инвариант 5: кулдаун бонуса ${ECON.bonus.cooldownMs} мс < 30000 мс`);
  // №6: EV/цена кейсов отличаются не более чем на 10 % — нет строго
  // доминируемого кейса.
  if (evPerPrice.length > 1 && Math.abs(evPerPrice[0] - evPerPrice[1]) > 0.10) {
    errs.push(`инвариант 6: EV/цена кейсов отличаются на ${(Math.abs(evPerPrice[0] - evPerPrice[1]) * 100).toFixed(1)} % > 10 %`);
  }
  return errs;
}
